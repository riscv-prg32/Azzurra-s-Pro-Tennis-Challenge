#!/usr/bin/env python3
"""Build every picture of the cartridge from the sources in tools/.

  python3 tools/build_art.py

Outputs (deterministic; both are committed):
  src/gen/art.inc      geometry, palettes, court pictures, skylines, sprites, font, cities
  assets/png/*.png     previews: every city's stadium as the panel shows it, and the sprites

The compact palette of a screen is laid out as
  [0, 48)               FIXED colours (32 for sprites, 16 for stands and interface)
  [48, 58)              the city's SURFACE colours (court roles, rival shirts)
  [58, 98)              the city's VIEW colours (its skyline)
and every entry owns one cell of the firmware's 6x6x6 cube (tools/palette.py).
Pictures are run-length rows that can be decoded one at a time: see docs/graphics.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from PIL import Image  # noqa: E402

import art_cities as ac  # noqa: E402
import art_court as ct  # noqa: E402
import art_sprites as sp  # noqa: E402
import geometry as g  # noqa: E402
import palette as pal  # noqa: E402
from art_common import TRANSPARENT, array, encode_rows, firmware_font, reduce_view, to565  # noqa: E402

SURF = pal.FIXED_COUNT
VIEWB = pal.FIXED_COUNT + pal.SURFACE_COLORS
PALETTE_SIZE = VIEWB + pal.VIEW_COLORS
FONT_FIRST, FONT_COUNT = 32, 64          # ' ' .. '_'


def city_palette(city: int, back: bool = False):
    """Solve the city's surface and view colours for one of its two views; return
    (palette RGB565 [PALETTE_SIZE], view picture as compact indices, local indices,
    local-to-compact map)."""
    roles = ac.surface_colors(city)
    shirt, shirtd = ac.CITIES[city][6], ac.CITIES[city][7]
    from art_common import hexrgb
    roles = roles + [hexrgb(shirt), hexrgb(shirtd)]
    surface = pal.solve_view([to565(c) for c in roles])
    taken = {**pal.fixed_holders(), **{pal.cube_index(c): c for c in surface}}
    view_img = ac.paint(city, back)
    colors, pixels = reduce_view(view_img, pal.VIEW_COLORS, taken, dither=False)
    # Each reduced colour is either one already held (fixed or surface) or a new one.
    fixed_cells = {pal.cube_index(c): i for i, c in enumerate(pal.FIXED_RGB565) if i != ct.FIX["clear"]}
    surf_cells = {pal.cube_index(c): SURF + i for i, c in enumerate(surface)}
    view_colors: list[int] = []
    local_to_compact = []
    for c in colors:
        cell = pal.cube_index(c)
        if cell in surf_cells:
            local_to_compact.append(surf_cells[cell])
        elif cell in fixed_cells:
            local_to_compact.append(fixed_cells[cell])
        else:
            local_to_compact.append(VIEWB + len(view_colors))
            view_colors.append(c)
    assert len(view_colors) <= pal.VIEW_COLORS, (city, len(view_colors))
    full = list(pal.FIXED_RGB565) + surface + view_colors
    while len(full) < PALETTE_SIZE:
        full.append(full[0])
    assert pal.check(full[:VIEWB + len(view_colors)]) == 0
    assert len(local_to_compact) <= 64, (city, len(local_to_compact))
    view = [[local_to_compact[v] for v in row] for row in pixels]
    return full, view, pixels, local_to_compact + [0] * (64 - len(local_to_compact))


def render_preview(palette565, view, court, sprites_drawn) -> Image.Image:
    img = Image.new("RGB", (g.GAME_W, g.GAME_H))
    px = img.load()
    for y in range(g.GAME_H):
        for x in range(g.GAME_W):
            if y < g.HUD_H:
                c = ct.FIX["hudbar"]
            elif y < g.COURT_Y:
                c = view[y - g.VIEW_Y][x]
            else:
                c = court[y - g.COURT_Y][x]
            px[x, y] = pal.rgb888(palette565[c])
    for spr, x0, y0 in sprites_drawn:
        for yy, row in enumerate(sp.to_indices(spr)):
            for xx, c in enumerate(row):
                if c != TRANSPARENT and 0 <= x0 + xx < g.GAME_W and 0 <= y0 + yy < g.GAME_H:
                    px[x0 + xx, y0 + yy] = pal.rgb888(pal.FIXED_RGB565[c])
    return img


def main() -> int:
    out = ["/* Generated by tools/build_art.py. Do not edit: change the sources in tools/. */"]
    png = ROOT / "assets/png"
    png.mkdir(parents=True, exist_ok=True)

    # ---- geometry ------------------------------------------------------------
    for name in ("HALF_L", "SERVICE", "SINGLES", "DOUBLES", "NET_POST", "NET_H_POST", "NET_H_MID", "F", "H",
                 "CAM_D", "HZ", "GAME_W", "GAME_H", "HUD_H", "VIEW_Y", "VIEW_H", "COURT_Y", "WALL_Y"):
        out.append(f"#define G_{name} {getattr(g, name)}")
    out.append(f"#define FIXED_COUNT {pal.FIXED_COUNT}\n#define SURFACE_BASE {SURF}\n#define VIEW_BASE {VIEWB}"
               f"\n#define PALETTE_SIZE {PALETTE_SIZE}\n#define SPR_TRANSPARENT {TRANSPARENT}")
    for name, i in pal.FIXED_INDEX.items():
        out.append(f"#define C_{name.upper()} {i}")
    for k, name in enumerate(("IN", "IN2", "OUT", "OUT2", "LINE", "LINED", "WEAR", "EDGE", "RIVAL", "RIVALD")):
        out.append(f"#define S_{name} {SURF + k}")

    # ---- cities: palettes and skylines, two views each -------------------------
    # Scene s = 2 * city + back: back = 0 is the broadcast camera behind the near
    # baseline, back = 1 the view from the far end (an online player of the far team).
    palettes, views, locals_, maps = [], [], [], []
    for city in range(len(ac.CITIES)):
        for back in (False, True):
            p, v, local, vmap = city_palette(city, back)
            palettes.append(p)
            views.append(v)
            locals_.append(local)
            maps += vmap
    out.append(f"#define CITY_COUNT {len(ac.CITIES)}")
    out.append(array("uint16_t", "city_palette", [c for p in palettes for c in p]))
    vdata: list[int] = []
    seen: dict = {}
    voffs: list[int] = []
    for v in locals_:
        voffs += encode_rows(v, 6, vdata, seen)
    out.append(array("uint8_t", "view_map", maps))
    assert len(vdata) < 65536
    out.append(array("uint8_t", "view_data", vdata))
    out.append(array("uint16_t", "view_rows", voffs))

    # ---- courts ---------------------------------------------------------------------
    cdata: list[int] = []
    seen = {}
    coffs: list[int] = []
    courts = []
    for kind in (ct.CLAY, ct.GRASS, ct.HARD):
        rows = ct.court_image(kind)
        courts.append(rows)
        coffs += encode_rows(rows, 6, cdata, seen)
    out.append(f"#define COURT_ROWS {g.COURT_IMG_H}")
    out.append(array("uint8_t", "court_data", cdata))
    out.append(array("uint16_t", "court_rows", coffs))
    names = [c[0] for c in ac.CITIES]
    rivals = [c[1] for c in ac.CITIES]
    out.append(array("uint8_t", "city_surface", [c[2] for c in ac.CITIES]))
    out.append(array("uint8_t", "city_night", [1 if c[3] else 0 for c in ac.CITIES]))

    def strings(name, items, width):
        flat = []
        for s in items:
            assert len(s) < width, s
            flat += [ord(ch) for ch in s] + [0] * (width - len(s))
        return f"static const char {name}[{len(items)}][{width}] = {{\n" + ",\n".join(
            "    {" + ",".join(str(v) for v in flat[i * width:(i + 1) * width]) + "}" for i in range(len(items))) + "\n};"
    out.append(strings("city_names", names, 16))
    out.append(strings("rival_names", rivals, 17))
    out.append(strings("surface_names", [ac.SURFACE_NAMES[k] for k in (ct.CLAY, ct.GRASS, ct.HARD)], 12))

    # ---- sprites ----------------------------------------------------------------------
    sprites: list[tuple[str, Image.Image]] = []
    for view in ("back", "front"):
        for name, img in zip(sp.FRAMES, sp.draw_player(view)):
            sprites.append((f"{view}_{name}", img))
    sprites.append(("ball", sp.ball_sprite()))
    sprites.append(("shadow", sp.ellipse_sprite(22, 6, "shadow")))
    sprites.append(("bshadow", sp.ellipse_sprite(6, 3, "shadow")))
    net, net_x, net_y = ct.net_sprite()
    sprites.append(("net", net))
    slots = ct.sponsor_slots()
    bw, bh = slots[0][2], slots[0][3]
    for k, s in enumerate(sp.SPONSORS):
        sprites.append((f"board{k}", sp.board_sprite(s, bw, bh, ("gold", "cyan", "white", "red", "green")[k])))
    sprites.append(("logo", sp.logo_sprite()))
    sprites.append(("trophy", sp.trophy_sprite()))
    for k, img in enumerate(sp.confetti()):
        sprites.append((f"conf{k}", img))
    sdata: list[int] = []
    seen = {}
    srows: list[int] = []
    sfirst, sw, sh = [], [], []
    for name, img in sprites:
        rows = sp.to_indices(img)
        sfirst.append(len(srows))
        sw.append(img.width)
        sh.append(img.height)
        srows += encode_rows(rows, 5, sdata, seen)
    assert len(sdata) < 65536
    for i, (name, _img) in enumerate(sprites):
        out.append(f"#define SPR_{name.upper()} {i}")
    out.append(f"#define SPR_COUNT {len(sprites)}\n#define SPR_FRAMES {len(sp.FRAMES)}")
    for k, name in enumerate(sp.FRAMES):
        out.append(f"#define PF_{name.upper()} {k}")
    out.append(f"#define NET_X {net_x}\n#define NET_Y {net_y}")
    out.append(f"#define BOARD_Y {slots[0][1]}\n#define BOARD_SLOTS {len(slots)}\n#define SPONSOR_COUNT {len(sp.SPONSORS)}")
    out.append(array("int16_t", "board_x", [s[0] for s in slots]))
    out.append(array("uint8_t", "spr_data", sdata))
    out.append(array("uint16_t", "spr_rows", srows))
    out.append(array("uint16_t", "spr_first", sfirst))
    out.append(array("uint16_t", "spr_w", sw))
    out.append(array("uint16_t", "spr_h", sh))

    # ---- font ---------------------------------------------------------------------------
    font = firmware_font()
    bits = []
    for code in range(FONT_FIRST, FONT_FIRST + FONT_COUNT):
        bits += font.get(chr(code), font[" "])
    out.append(array("uint8_t", "font_bits", bits))

    (ROOT / "src/gen").mkdir(parents=True, exist_ok=True)
    (ROOT / "src/gen/art.inc").write_text("\n".join(out) + "\n", encoding="utf-8")

    # ---- previews -------------------------------------------------------------------------
    for back, name in ((0, "cities.png"), (1, "cities_back.png")):
        sheet = Image.new("RGB", (g.GAME_W * 2, g.GAME_H * 7), (0, 0, 0))
        for city in range(len(ac.CITIES)):
            kind = ac.CITIES[city][2]
            draw = [(net, net_x, net_y)]
            draw += [(sprites[sp_index("board", k % len(sp.SPONSORS), sprites)][1], s[0], s[1])
                     for k, s in enumerate(slots)]
            k = 2 * city + back
            img = render_preview(palettes[k], views[k], courts[(ct.CLAY, ct.GRASS, ct.HARD).index(kind)], draw)
            sheet.paste(img, ((city % 2) * g.GAME_W, (city // 2) * g.GAME_H))
        sheet.save(png / name)
    big = Image.new("RGBA", (360, 200), (40, 40, 48, 255))
    x = y = 2
    rowh = 0
    for name, img in sprites:
        if name.startswith("board") or name == "net" or name == "logo":
            continue
        if x + img.width > 358:
            x, y = 2, y + rowh + 2
            rowh = 0
        big.alpha_composite(img, (x, y))
        x += img.width + 2
        rowh = max(rowh, img.height)
    big.resize((720, 400), Image.NEAREST).save(png / "sprites.png")
    print(f"art: {len(ac.CITIES)} cities x 2 views, views {len(vdata)} B, courts {len(cdata)} B, "
          f"{len(sprites)} sprites {len(sdata)} B, palette {PALETTE_SIZE} entries")
    return 0


def sp_index(prefix: str, k: int, sprites) -> int:
    for i, (name, _img) in enumerate(sprites):
        if name == f"{prefix}{k}":
            return i
    raise KeyError(prefix)


if __name__ == "__main__":
    sys.exit(main())
