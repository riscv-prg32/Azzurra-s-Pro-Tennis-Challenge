/*
 * Azzurra's Pro Tennis Challenge - PRG32 portable cartridge, 128 KiB profile.
 *
 * Azzurra and her partner Viola take on fourteen doubles pairs in fourteen cities,
 * from Napoli to the final in Athens, on clay, grass and hard courts, by day and
 * under floodlights. Singles or doubles, against the computer or online: up to four
 * consoles meet through the PRG32 Multiplayer Server, and the computer fills any
 * free place.
 *
 * The rules, the ball and the computer players are in az_core.h; the online
 * lockstep in az_net.h; the sequencer in az_music.h; every picture, palette and the
 * geometry in gen/art.inc, generated by tools/build_art.py. This file shows the game.
 *
 * The renderer works one screen row at a time:
 *
 *   1. A row buffer in cartridge memory is filled with the row's background: the
 *      score bar, a row of the city's skyline, or a row of the stadium and court,
 *      each a run-length row decoded on its own.
 *   2. Every sprite crossing the row is scaled into it, far to near, so that the
 *      net hides a far player's feet and a near player stands in front of the net.
 *   3. Text goes on top, and the part of the row that changed reaches the firmware
 *      as runs of one indexed colour (prg32_gfx_rect_indexed), or as one 8-bit
 *      indexed sprite when the row is too busy.
 *
 * Nothing is ever erased and no picture is ever held whole: a moved sprite's old
 * pixels vanish because its rows are rebuilt. Only rows that changed are sent,
 * which is what decides the frame rate on the ESP32-C6's SPI panel.
 *
 * Colours: every entry of the screen's compact palette owns one cell of the
 * firmware's 6x6x6 cube, and the cell is set to the exact colour
 * (prg32_palette_set), so the indexed framebuffer of the ESP32-C6 and the direct
 * colour one of QEMU show the same picture (docs/graphics.md).
 *
 * Portable cartridges have no relocations: no pointer may appear in initialised
 * static data (tools/check_relocatable.py proves it).
 */
