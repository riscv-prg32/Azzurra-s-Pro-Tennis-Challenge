static void lobby_step(uint32_t pressed) {
    net_lobby_t *m = &v.net.mine;
    uint32_t ids[NET_PEERS + 1];
    net_lobby_t info[NET_PEERS + 1];
    int n = net_lobby_list(ids, info, 0);
    int host = n > 0 && ids[0] == v.net.my_id;
    const net_lobby_t *h = n > 0 ? &info[0] : m;
    /* This console's own match settings: they are the match when it hosts, and
     * what the lobby shows before any host is known. Other consoles ignore a
     * client's. */
    m->doubles = v.doubles;
    m->city = v.exhibition_city;
    m->games = v.games_to_win;
    /* Input: rows, then the change. The host's match settings are the host's only. */
    if (!m->start) {
        int dir = (pressed & PRG32_BTN_DOWN) ? 1 : (pressed & PRG32_BTN_UP) ? -1 : 0;
        if (dir) {
            do v.net.row = (uint8_t)((v.net.row + LOBBY_ROWS + dir) % LOBBY_ROWS);
            while (!host && v.net.row >= LOBBY_MATCH && v.net.row <= LOBBY_GAMES);
            az_sfx_play(&v.music, SFX_MENU, 0, 0);
        }
        int side = (pressed & PRG32_BTN_RIGHT) ? 1 : (pressed & PRG32_BTN_LEFT) ? -1 : 0;
        if (side) {
            if (v.net.row == LOBBY_TEAM) m->team = (uint8_t)!m->team;
            else if (v.net.row == LOBBY_MATCH) v.doubles = (uint8_t)!v.doubles;
            else if (v.net.row == LOBBY_CITY) v.exhibition_city = (uint8_t)((v.exhibition_city + CITY_COUNT + side) % CITY_COUNT);
            else if (v.net.row == LOBBY_GAMES) v.games_to_win = (uint8_t)(v.games_to_win == 1 ? (side > 0 ? 2 : 4) : v.games_to_win == 2 ? (side > 0 ? 4 : 1) : (side > 0 ? 1 : 2));
            az_sfx_play(&v.music, SFX_MENU, 0, 0);
        }
        if (pressed & PRG32_BTN_A) {
            if (v.net.row == LOBBY_LEAVE) {
                title_screen();
                return;
            }
            m->ready = (uint8_t)!m->ready;        /* A on any other row: ready or not */
            az_sfx_play(&v.music, SFX_SELECT, 0, 0);
        }
        if (pressed & PRG32_BTN_B) {
            if (m->ready) m->ready = 0;
            else {
                title_screen();
                return;
            }
        }
    }
    /* The start. */
    const char *footer = "";
    char cd[24];
    if (!v.net.my_id) {
        footer = "CONNECTING TO THE SERVER...";
    } else if (host) {
        if (!m->start) {
            uint32_t rids[NET_PEERS + 1];
            net_lobby_t rinfo[NET_PEERS + 1];
            int rn = net_lobby_list(rids, rinfo, 1);
            if (rn > NET_MAX) rn = NET_MAX;
            int map = m->ready ? net_slot_map(rinfo, rn, m->doubles) : -1;
            uint16_t hash = net_roster_hash(rids, rn);
            if (map >= 0) {
                if (!v.net.countdown_on || m->hash != hash || m->map != (uint16_t)map) {
                    v.net.countdown_on = 1;
                    v.net.countdown = NET_COUNTDOWN_TICKS;
                    m->hash = hash;
                    m->map = (uint16_t)map;
                } else if (--v.net.countdown == 0) {
                    v.seed = v.seed * 1103515245u + 12345u + v.app_tick;
                    m->seed = (uint16_t)(v.seed >> 8);
                    m->tag = (uint8_t)(1 + (v.seed >> 3) % 15u);
                    m->count = (uint8_t)rn;
                    m->start = 1;
                    v.net.start_wait = 0;
                    v.net.roster_n = (uint8_t)rn;
                    for (int i = 0; i < rn; ++i) v.net.roster[i] = rids[i];
                }
                int secs = (v.net.countdown + 29) / 30;
                int k = append(cd, 0, "STARTING IN ");
                cd[k++] = (char)('0' + secs);
                cd[k] = 0;
                footer = cd;
            } else {
                v.net.countdown_on = 0;
                footer = !m->ready ? "PRESS A WHEN READY"
                         : rn < 2 ? "WAITING FOR PLAYERS"
                         : m->doubles ? "TWO PLAYERS A SIDE AT MOST" : "1 VS 1: ONE PLAYER EACH SIDE";
            }
        } else {
            /* Everyone answers the start by entering the match. */
            int all = 1;
            for (int i = 0; i < v.net.roster_n; ++i) {
                if (v.net.roster[i] == v.net.my_id) continue;
                int k = net_find(v.net.roster[i]);
                uint8_t sym[NET_W];
                unsigned tag = 0;
                if (k < 0 || net_unpack_match(&v.net.peer[k], sym, &tag) < 0 || tag != m->tag) all = 0;
            }
            if (all) {
                net_lobby_t cfg = *m;
                m->start = 0;
                m->ready = 0;
                net_begin_match(&cfg, v.net.roster, v.net.roster_n);
                return;
            }
            if (++v.net.start_wait > NET_START_TIMEOUT_TICKS) {
                m->start = 0;
                m->ready = 0;
                v.net.countdown_on = 0;
            }
            footer = "STARTING...";
        }
    } else {
        m->start = 0;
        footer = m->ready ? "WAITING FOR THE HOST" : "PRESS A WHEN READY";
        if (m->ready && h->start) {
            /* The players the host named: the ready ones and those already in. */
            uint32_t rids[NET_PEERS + 1];
            int rn = 0;
            rids[rn++] = v.net.my_id;
            for (int i = 0; i < v.net.peer_count; ++i) {
                net_lobby_t l;
                uint8_t sym[NET_W];
                unsigned tag = 0;
                int ok = (net_unpack_lobby(&v.net.peer[i], &l) == 0 && l.ready) ||
                         (net_unpack_match(&v.net.peer[i], sym, &tag) >= 0 && tag == h->tag);
                if (ok) rids[rn++] = v.net.peer_id[i];
            }
            for (int i = 1; i < rn; ++i)
                for (int k = i; k > 0 && rids[k - 1] > rids[k]; --k) {
                    uint32_t t = rids[k];
                    rids[k] = rids[k - 1];
                    rids[k - 1] = t;
                }
            if (rn > NET_MAX) rn = NET_MAX;
            int me = -1;
            for (int i = 0; i < rn; ++i)
                if (rids[i] == v.net.my_id) me = i;
            int named = 0;
            for (int s = 0; s < 4; ++s) named |= (int)((h->map >> (4 * s)) & 15u) == me;
            if (rn == h->count && net_roster_hash(rids, rn) == h->hash && me >= 0 && named) {
                net_lobby_t cfg = *h;
                m->ready = 0;
                net_begin_match(&cfg, rids, rn);
                return;
            }
            footer = "STARTING...";
        }
    }
    /* The panel. */
    char buf[TEXT_COLS + 1];
    int k;
    if (!v.net.my_id) lobby_line(5, "PRG32 MULTIPLAYER SERVER", C_GREY);
    else {
        k = append(buf, 0, "IN THE LOBBY: ");
        buf[k++] = (char)('0' + (n > 9 ? 9 : n));
        append(buf, k, n == 1 ? " CONSOLE" : " CONSOLES");
        lobby_line(5, buf, C_GREY);
    }
    for (int r = 0; r < LOBBY_ROWS; ++r) {
        int locked = !host && r >= LOBBY_MATCH && r <= LOBBY_GAMES;
        switch (r) {
        case LOBBY_TEAM: k = append(buf, 0, "TEAM: "); append(buf, k, m->team ? "RIVALS" : "AZZURRA"); break;
        case LOBBY_MATCH: append(buf, 0, h->doubles ? "MATCH: 2 VS 2" : "MATCH: 1 VS 1"); break;
        case LOBBY_CITY: k = append(buf, 0, "CITY: "); append(buf, k, city_names[h->city % CITY_COUNT]); break;
        case LOBBY_GAMES: k = append(buf, 0, "GAMES PER SET: "); buf[k++] = (char)('0' + h->games); buf[k] = 0; break;
        case LOBBY_READY: append(buf, 0, m->ready ? "READY: YES" : "READY: NO"); break;
        default: append(buf, 0, "LEAVE"); break;
        }
        int color = r == v.net.row ? C_GOLD : locked ? C_GREY : C_CREAM;
        if (r == v.net.row) {
            char sel[TEXT_COLS + 1];
            k = append(sel, 0, "> ");
            k = append(sel, k, buf);
            append(sel, k, " <");
            lobby_line(7 + r, sel, color);
        } else {
            lobby_line(7 + r, buf, color);
        }
    }
    for (int i = 0; i < NET_MAX; ++i) {
        /* Columns: who, team, ready, host; the same width on every line. */
        k = append(buf, 0, i >= n ? "" : ids[i] == v.net.my_id ? "YOU       " : "PLAYER    ");
        if (i < n) {
            if (ids[i] != v.net.my_id) buf[7] = (char)('1' + i);
            k = append(buf, k, info[i].team ? "RIVALS   " : "AZZURRA  ");
            k = append(buf, k, info[i].ready ? "READY" : "     ");
            append(buf, k, i == 0 ? "  HOST" : "      ");
        }
        lobby_line(15 + i, buf, i < n && ids[i] == v.net.my_id ? C_CYAN : C_CREAM);
    }
    lobby_line(20, footer, C_BALL);
    lobby_line(21, "A: READY  B: BACK  LEFT/RIGHT: SET", C_GREY);
}

/* ---- online: the match ------------------------------------------------------------------- */

static void update_step(const uint32_t held[4], const uint32_t pressed[4], uint32_t ui_pressed);

static void net_match_frame(uint32_t buttons, uint32_t fresh) {
    uint32_t now = prg32_ticks_ms();
    net_lock_t *lk = &v.net.lock;
    /* Leaving: START asks, B confirms (SELECT is START on PRG32). The match does not
     * stop for anyone. */
    if (fresh & PRG32_BTN_START) {
        v.net.prompt = (uint8_t)!v.net.prompt;
        if (v.net.prompt) {
            text_panel(11, 13, 6, 34);
            text_center(11, "ONLINE: NO PAUSE", C_GOLD);
            text_center(12, "B: LEAVE THE MATCH", C_CREAM);
            text_center(13, "START: PLAY ON", C_CREAM);
        } else {
            for (int cy = 11; cy <= 13; ++cy) text_clear_line(cy);
        }
    }
    if (v.net.prompt && (fresh & PRG32_BTN_B)) {
        title_screen();
        return;
    }
    /* The other consoles' inputs. */
    uint32_t id = prg32_multiplayer_local_player_id();
    if (id != v.net.my_id) {
        if (id || now - v.net.seen_ms[lk->me] > NET_LOST_MS) {
            net_abort("CONNECTION LOST");
            return;
        }
    } else {
        v.net.seen_ms[lk->me] = now;
    }
    for (int k = 0; k < v.net.roster_n; ++k) {
        if (k == lk->me) continue;
        int i = net_find(v.net.roster[k]);
        if (i < 0) {
            if (now - v.net.seen_ms[k] > NET_LOST_MS) {
                net_abort("A PLAYER WAS LOST");
                return;
            }
            continue;
        }
        v.net.seen_ms[k] = now;
        int r = net_lock_receive(lk, k, &v.net.peer[i]);
        /* At the start, the others may still be in the lobby, about to come in. */
        int starting = lk->tick <= NET_D && now - v.net.start_ms < NET_START_TIMEOUT_TICKS * AZ_TICK_MS + 1000u;
        if (r == -1 && !starting && lk->known[k] <= lk->tick) {     /* gone back to the lobby, and needed */
            net_abort("A PLAYER LEFT");
            return;
        }
        if (r == -2) {
            net_abort("OUT OF STEP");
            return;
        }
    }
    /* Run every tick whose inputs are all here. */
    while (v.tick_accum >= AZ_TICK_MS) {
        if (!net_lock_ready(lk)) break;
        if (lk->known[lk->me] == lk->tick + NET_D) {
            net_lock_local(lk, to_core(buttons | v.pending_pressed));
            v.pending_pressed = 0;
        }
        v.tick_accum -= AZ_TICK_MS;
        uint32_t h[4], p[4];
        for (int s = 0; s < 4; ++s) {
            unsigned c = v.net.slot[s];
            h[s] = c < NET_MAX ? net_lock_held(lk, (int)c, lk->tick) : 0;
            p[s] = c < NET_MAX ? net_lock_pressed(lk, (int)c, lk->tick) : 0;
        }
        update_step(h, p, 0);
        lk->tick++;
        v.net.last_advance_ms = now;
        if (v.net.waiting) {
            v.net.waiting = 0;
            text_clear_line(16);
        }
        if (v.net.finished || !v.net.in_match) break;
    }
    if (v.net.in_match && !v.net.finished && !v.net.waiting && now - v.net.last_advance_ms > NET_WAIT_MS) {
        v.net.waiting = 1;
        text_panel(16, 16, 8, 32);
        text_center(16, "WAITING FOR PLAYERS", C_GOLD);
    }
}

static void net_publish(void) {
    net_snap_t s;
    if (v.net.in_match) net_lock_snapshot(&v.net.lock, &s);
    else net_pack_lobby(&s, &v.net.mine);
    prg32_multiplayer_set_local_state(s.x, s.y, s.sprite, s.flags);
    prg32_multiplayer_set_input(s.input);
}

/* ---- one tick ------------------------------------------------------------------------------ */

/* held/pressed: the four players' inputs (AZ_* bits); ui_pressed: this console's new
 * presses (PRG32_BTN_*), for the menus. */
static void update_step(const uint32_t held[4], const uint32_t pressed[4], uint32_t ui_pressed) {
    az_game_t *g = &v.game;
    static const uint32_t none[4] = {0, 0, 0, 0};
    v.app_tick++;
    az_music_tick(&v.music);
    if (v.banner_ticks && --v.banner_ticks == 0 && (v.app == APP_PLAY || v.app == APP_DEMO)) {
        text_clear_line(7);
        text_clear_line(8);
    }
    switch (v.app) {
    case APP_TITLE:
        if (ui_pressed) v.idle = 0;
        else if (++v.idle > DEMO_IDLE_TICKS) {
            demo_screen();
            break;
        }
        menu_input(ui_pressed);
        break;
    case APP_DEMO:
        if (ui_pressed & ANY_BUTTON) {
            title_screen();
            break;
        }
        az_tick(g, none, none);
        handle_events();
        if (g->state == PS_DEAD && g->timer > 50) {
            if (g->match_over) demo_screen();
            else az_next_point(g);
        }
        hud_update();
        if ((v.app_tick & 31u) == 0) text_center(23, "DEMO", C_GOLD);
        if ((v.app_tick & 31u) == 16) text_center(23, "    ", C_GOLD);
        break;
    case APP_INTRO:
        /* Online, every console leaves the intro on the same tick. */
        if (v.app_tick > NET_INTRO_TICKS || (!v.online && (ui_pressed & ANY_BUTTON))) play_screen();
        break;
    case APP_PLAY:
        if (!v.online && (ui_pressed & PRG32_BTN_START)) {
            set_app(APP_PAUSE);
            text_panel(11, 13, 6, 34);
            text_center(11, "PAUSED", C_GOLD);
            text_center(12, "START: RESUME", C_CREAM);
            text_center(13, "B: QUIT TO TITLE", C_CREAM);
            break;
        }
        az_tick(g, held, pressed);
        handle_events();
        if (g->state == PS_DEAD) {
            if (g->match_over) {
                if (g->timer > 90) {
                    if (g->match_winner == v.my_team) {
                        if (!v.exhibition && v.round + 1 >= ROUNDS) champion_screen();
                        else roundwon_screen();
                    } else {
                        gameover_screen();
                    }
                }
            } else if (g->timer > 50) {
                az_next_point(g);
            }
        }
        hud_update();
        break;
    case APP_PAUSE:
        if (ui_pressed & PRG32_BTN_START) {
            set_app(APP_PLAY);
            for (int cy = 11; cy <= 13; ++cy) text_clear_line(cy);
        } else if (ui_pressed & PRG32_BTN_B) {     /* PRG32_BTN_SELECT is START itself */
            title_screen();
        }
        break;
    case APP_ROUNDWON:
        az_tick(g, none, none);
        if (v.app_tick > RESULT_GUARD_TICKS && (ui_pressed & ANY_BUTTON)) {
            az_music_stop(&v.music);
            if (v.online) {
                if (ui_pressed & PRG32_BTN_A) lobby_screen();
                else title_screen();
            } else if (v.exhibition) {
                title_screen();
            } else {
                v.round++;
                intro_screen();
            }
        }
        break;
    case APP_GAMEOVER:
        az_tick(g, none, none);
        if (v.app_tick > RESULT_GUARD_TICKS) {
            if (v.online && (ui_pressed & PRG32_BTN_A)) {
                az_music_stop(&v.music);
                lobby_screen();
            } else if (!v.exhibition && (ui_pressed & PRG32_BTN_A)) {
                az_music_stop(&v.music);
                intro_screen();
            } else if (ui_pressed & (PRG32_BTN_B | PRG32_BTN_START | (v.exhibition ? PRG32_BTN_A : 0))) {
                title_screen();
            }
        }
        break;
    case APP_CHAMPION:
        for (int i = 0; i < 24; ++i) {
            v.conf_y[i] = (uint8_t)(v.conf_y[i] + 1 + (i & 1));
            if (v.conf_y[i] > 196) v.conf_y[i] = 0;
        }
        if (v.app_tick > RESULT_GUARD_TICKS + 15 && (ui_pressed & ANY_BUTTON)) title_screen();
        break;
    case APP_LOBBY:
        lobby_step(ui_pressed);
        break;
    case APP_NETMSG:
        if (ui_pressed & PRG32_BTN_A) {
            if (v.net.joined) lobby_screen();
            else title_screen();
        } else if (ui_pressed & PRG32_BTN_B) {
            title_screen();
        }
        break;
    default:
        break;
    }
}

