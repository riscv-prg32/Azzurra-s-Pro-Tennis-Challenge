static int net_peer_phase(int i) { return v.net.peer[i].flags & 3u; }

static int net_find(uint32_t id) {
    for (int i = 0; i < v.net.peer_count; ++i)
        if (v.net.peer_id[i] == id) return i;
    return -1;
}

static void net_poll(void) {
    int n = prg32_multiplayer_get_peer_count();
    if (n > NET_PEERS) n = NET_PEERS;
    int k = 0;
    for (int i = 0; i < n; ++i) {
        prg32_player_state_t st;
        if (prg32_multiplayer_get_peer(i, &st) != 0 || !st.player_id) continue;
        v.net.peer_id[k] = st.player_id;
        v.net.peer[k].x = st.x;
        v.net.peer[k].y = st.y;
        v.net.peer[k].sprite = st.sprite;
        v.net.peer[k].flags = st.flags;
        v.net.peer[k].input = (uint8_t)(st.input & 0x7Fu);
        ++k;
    }
    v.net.peer_count = (uint8_t)k;
}

/* The consoles in the lobby (this one included), by player ID: the lowest is the host.
 * ready_only: only those ready to play. Returns how many. */
static int net_lobby_list(uint32_t *ids, net_lobby_t *info, int ready_only) {
    int n = 0;
    if (v.net.my_id && (!ready_only || v.net.mine.ready)) {
        ids[n] = v.net.my_id;
        info[n++] = v.net.mine;
    }
    for (int i = 0; i < v.net.peer_count; ++i) {
        net_lobby_t l;
        if (net_peer_phase(i) != NET_PHASE_LOBBY || net_unpack_lobby(&v.net.peer[i], &l) != 0) continue;
        if (ready_only && !l.ready) continue;
        ids[n] = v.net.peer_id[i];
        info[n++] = l;
    }
    for (int i = 1; i < n; ++i) {             /* insertion sort, a handful */
        for (int k = i; k > 0 && ids[k - 1] > ids[k]; --k) {
            uint32_t t = ids[k];
            ids[k] = ids[k - 1];
            ids[k - 1] = t;
            net_lobby_t tl = info[k];
            info[k] = info[k - 1];
            info[k - 1] = tl;
        }
    }
    return n;
}

/* The slot map for these consoles and teams, or -1 if they cannot make a match:
 * singles needs one console on each side; doubles two to four, two a side at most. */
static int net_slot_map(const net_lobby_t *info, int n, int doubles) {
    if (n < 2 || n > NET_MAX || (!doubles && n != 2)) return -1;
    unsigned map = 0xFFFFu;
    int used[2] = {0, 0};
    for (int i = 0; i < n; ++i) {
        int t = info[i].team & 1;
        if (used[t] >= (doubles ? 2 : 1)) return -1;
        int slot = t * 2 + used[t]++;
        map = (map & ~(15u << (4 * slot))) | ((unsigned)i << (4 * slot));
    }
    return (int)map;
}

static void net_begin_match(const net_lobby_t *cfg, const uint32_t *ids, int n) {
    az_game_t *g = &v.game;
    v.net.roster_n = (uint8_t)n;
    int me = 0;
    for (int i = 0; i < n; ++i) {
        v.net.roster[i] = ids[i];
        if (ids[i] == v.net.my_id) me = i;
        v.net.seen_ms[i] = prg32_ticks_ms();
    }
    v.my_team = AZ_NEAR;
    for (int s = 0; s < 4; ++s) {
        unsigned c = (cfg->map >> (4 * s)) & 15u;
        v.net.slot[s] = (uint8_t)(c < (unsigned)n ? c : NET_CPU);
        g->p[s].human = (uint8_t)(c < (unsigned)n);
        g->p[s].rot = (uint8_t)(g->p[s].human && s >= 2);
        if ((int)c == me) v.my_team = (uint8_t)(s >= 2 ? AZ_FAR : AZ_NEAR);
    }
    net_lock_start(&v.net.lock, n, me, cfg->tag);
    v.net.in_match = 1;
    v.net.finished = 0;
    v.net.prompt = 0;
    v.net.waiting = 0;
    v.net.last_advance_ms = v.net.start_ms = prg32_ticks_ms();
    v.online = 1;
    v.exhibition = 1;
    int city = cfg->city % CITY_COUNT;
    set_app(APP_INTRO);
    az_music_stop(&v.music);
    scene_view(city, v.my_team == AZ_FAR);
    az_new_match(g, city, city_surface[city], cfg->games, 0x5EED0000u ^ cfg->seed, cfg->seed & 1u, !cfg->doubles);
    intro_show(city);
}

