static void menu_input(uint32_t pressed) {
    int changed = 0;
    if (pressed & PRG32_BTN_UP) {
        v.menu = (uint8_t)((v.menu + MENU_COUNT - 1) % MENU_COUNT);
        changed = 1;
    }
    if (pressed & PRG32_BTN_DOWN) {
        v.menu = (uint8_t)((v.menu + 1) % MENU_COUNT);
        changed = 1;
    }
    int dir = (pressed & PRG32_BTN_RIGHT) ? 1 : (pressed & PRG32_BTN_LEFT) ? -1 : 0;
    if (dir) {
        if (v.menu == MENU_EXHIBITION) v.exhibition_city = (uint8_t)((v.exhibition_city + CITY_COUNT + dir) % CITY_COUNT);
        else if (v.menu == MENU_GAMES) v.games_to_win = (uint8_t)(v.games_to_win == 1 ? (dir > 0 ? 2 : 4) : v.games_to_win == 2 ? (dir > 0 ? 4 : 1) : (dir > 0 ? 1 : 2));
        else if (v.menu == MENU_MATCH) v.doubles = (uint8_t)!v.doubles;
        changed = 1;
    }
    if (changed) {
        az_sfx_play(&v.music, SFX_MENU, 0, 0);
        title_menu();
        v.idle = 0;
    }
    if (pressed & (PRG32_BTN_A | PRG32_BTN_START)) {
        az_sfx_play(&v.music, SFX_SELECT, 0, 0);
        if (v.menu == MENU_TOUR) {
            v.exhibition = 0;
            v.round = 0;
            intro_screen();
        } else if (v.menu == MENU_EXHIBITION) {
            v.exhibition = 1;
            intro_screen();
        } else if (v.menu == MENU_ONLINE) {
            net_enter();
        } else {
            menu_input(PRG32_BTN_RIGHT);
        }
    }
}

