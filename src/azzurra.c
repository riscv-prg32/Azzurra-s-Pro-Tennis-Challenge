void azzurra_init(void) {
    uint8_t *raw = (uint8_t *)&v;
    for (unsigned i = 0; i < sizeof(v); ++i) raw[i] = 0;
    v.row.palette = v.palette;
    v.row.palette_count = PALETTE_SIZE;
    v.row.width = W;
    v.row.height = 1;
    v.row.frame_count = 1;
    v.row.bits_per_pixel = PRG32_SPRITE_BPP_8;
    v.row.transparent_index = -1;
    v.row.pixels = v.line;
    for (int y = 0; y < TEXT_ROWS; ++y)
        for (int x = 0; x < TEXT_COLS; ++x) v.text[y][x] = ' ';
    v.games_to_win = 4;
    v.doubles = 1;
    v.scene_city = 0xFF;
    v.demo_city = 2;
    v.seed = 0xA22A1987u;
    az_music_init(&v.music);
    v.last_ms = prg32_ticks_ms();
    v.last_input = prg32_input_read();
    title_screen();
}

void azzurra_update(void) {
    uint32_t buttons = prg32_input_read();
    uint32_t fresh = buttons & ~v.last_input;
    /* A press waits for the next tick: a frame shorter than a tick runs none. */
    v.pending_pressed |= fresh;
    v.last_input = buttons;
    uint32_t now = prg32_ticks_ms();
    v.tick_accum += now - v.last_ms;
    v.last_ms = now;
    if (v.tick_accum > AZ_TICK_MS * MAX_CATCH_UP) v.tick_accum = AZ_TICK_MS * MAX_CATCH_UP;
    if (v.net.joined) {
        net_poll();
        if (!v.net.in_match) v.net.my_id = prg32_multiplayer_local_player_id();
    }
    if (v.net.in_match && !v.net.finished) {
        net_match_frame(buttons, fresh);
    } else {
        while (v.tick_accum >= AZ_TICK_MS) {
            v.tick_accum -= AZ_TICK_MS;
            uint32_t pressed = v.pending_pressed;
            v.pending_pressed = 0;
            uint32_t h[4] = {to_core(buttons), 0, 0, 0};
            uint32_t p[4] = {to_core(pressed), 0, 0, 0};
            update_step(h, p, pressed);
            if (v.net.in_match && !v.net.finished) break;    /* a match just started */
        }
    }
    if (v.net.joined) {
        net_publish();
        prg32_multiplayer_tick();
    }
}

void azzurra_draw(void) {
    v.count = 0;
    switch (v.app) {
    case APP_TITLE:
    case APP_LOBBY:
        add_static();
        for (int i = 0; i < 4; ++i) add_player(i);
        if (v.app == APP_TITLE) sprite_add_1x(SPR_LOGO, (W - spr_w[SPR_LOGO]) / 2, 14, 32000);
        break;
    case APP_CHAMPION: {
        add_static();
        for (int i = 0; i < 4; ++i) add_player(i);
        sprite_add_1x(SPR_TROPHY, (W - spr_w[SPR_TROPHY]) / 2, 92, 30000);
        for (int i = 0; i < 24; ++i) sprite_add_1x(SPR_CONF0 + v.conf_k[i], 35 + v.conf_x[i], v.conf_y[i], 31000 + i);
        break;
    }
    default:
        add_match();
        break;
    }
    render();
}
