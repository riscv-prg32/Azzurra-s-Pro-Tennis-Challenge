static void handle_events(void) {
    az_game_t *g = &v.game;
    char call[24];
    for (int i = 0; i < g->event_count; ++i) {
        const az_event_t *e = &g->events[i];
        switch (e->type) {
        case EV_TOSS: sfx(SFX_TOSS, e->x); break;
        case EV_HIT:
            sfx(e->value == SHOT_LOB ? SFX_LOB : e->value == SHOT_SERVE || e->value == SHOT_SMASH ? SFX_SERVE
                : e->value == SHOT_VOLLEY ? SFX_VOLLEY : SFX_FLAT, e->x);
            break;
        case EV_BOUNCE: if (e->value < 3) sfx(SFX_BOUNCE, e->x); break;
        case EV_NET: sfx(SFX_NET, e->x); break;
        case EV_OUT: sfx(SFX_OUT, e->x); say(7, "OUT!", C_RED, 50); break;
        case EV_FAULT: sfx(SFX_FAULT, e->x); say(7, "FAULT", C_RED, 50); break;
        case EV_DOUBLE_FAULT: say(7, "DOUBLE FAULT", C_RED, 55); break;
        case EV_LET: sfx(SFX_LET, e->x); say(7, "LET", C_GOLD, 50); break;
        case EV_POINT:
            if (v.app == APP_PLAY) sfx(e->value == v.my_team ? SFX_WON : SFX_LOST, 0);
            if (e->value == v.my_team || v.app == APP_DEMO) sfx(SFX_APPLAUSE, 0);
            break;
        case EV_GAME: sfx(SFX_GAME, 0); break;
        default: break;
        }
    }
    /* After a point: the umpire's call. */
    for (int i = 0; i < g->event_count; ++i) {
        const az_event_t *e = &g->events[i];
        if (e->type == EV_MATCH) {
            int mine = e->value == v.my_team || v.app == APP_DEMO;
            say(7, mine ? "GAME, SET AND MATCH!" : "MATCH TO THE RIVALS", mine ? C_GOLD : C_RED, 90);
            if (v.online && !mine) say(7, e->value == AZ_NEAR ? "MATCH TO AZZURRA" : "MATCH TO THE RIVALS", C_RED, 90);
        } else if (e->type == EV_GAME) {
            say(7, e->value == 0 ? "GAME AZZURRA" : "GAME RIVALS", C_GOLD, 60);
        } else if (e->type == EV_TIEBREAK) {
            say(7, "TIE-BREAK!", C_GOLD, 60);
        } else if (e->type == EV_POINT && i == g->event_count - 1) {
            int had_banner = v.banner_ticks > 0;
            az_call(g, call);
            if (!had_banner) say(7, call, C_CREAM, 45);
            else {
                text_clear_line(8);
                text_panel(8, 8, 8, 32);
                text_center(8, call, C_CREAM);
            }
        }
    }
}

