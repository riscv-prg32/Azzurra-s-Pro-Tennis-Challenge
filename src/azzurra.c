static uint32_t to_core(uint32_t b) {
    uint32_t in = 0;
    if (b & PRG32_BTN_LEFT) in |= AZ_LEFT;
    if (b & PRG32_BTN_RIGHT) in |= AZ_RIGHT;
    if (b & PRG32_BTN_UP) in |= AZ_UP;
    if (b & PRG32_BTN_DOWN) in |= AZ_DOWN;
    if (b & PRG32_BTN_A) in |= AZ_A;
    if (b & PRG32_BTN_B) in |= AZ_B;
    return in;
}

