/* ---- colours ------------------------------------------------------------------- */

static void city_load(int city, int rev) {
    v.city = (uint8_t)city;
    v.rev = (uint8_t)rev;
    v.court = city_surface[city];
    const uint16_t *pal = city_palette + (city * 2 + rev) * PALETTE_SIZE;
    for (int i = 0; i < PALETTE_SIZE; ++i) {
        uint16_t c = pal[i];
        v.palette[i] = c;
        /* The firmware's quantiser (tools/palette.py: cube_index). */
        static const uint16_t named[8] = {0x0000, 0xffff, 0xf800, 0x07e0, 0x001f, 0xffe0, 0x07ff, 0xf81f};
        uint8_t cell = 0;
        int k;
        for (k = 0; k < 8 && named[k] != c; ++k) {}
        if (k < 8) {
            cell = (uint8_t)k;
        } else {
            unsigned r = ((c >> 11) & 31u) * 5u / 31u, g = ((c >> 5) & 63u) * 5u / 63u, b = (c & 31u) * 5u / 31u;
            cell = (uint8_t)(16u + r * 36u + g * 6u + b);
        }
        v.cell[i] = cell;
    }
    for (int i = 0; i < PALETTE_SIZE; ++i) prg32_palette_set(v.cell[i], v.palette[i]);
    /* Player colours: Azzurra in azure with blonde hair, Viola in azure with brown,
     * the rivals in their city's colours. */
    static const uint8_t hairs[4] = {C_BLONDE, C_BROWN, C_DARK, C_GREYD};
    static const uint8_t skins[3][2] = {{C_SKIN, C_SKIND}, {C_SKIND, C_BROWN}, {C_SKINL, C_SKIN}};
    for (int t = 0; t < 4; ++t) {
        for (int i = 0; i < 32; ++i) v.tint[t][i] = (uint8_t)i;
        int hair = t == 0 ? C_BLONDE : t == 1 ? C_BROWN : hairs[(city * 3 + t) & 3];
        int skin = t < 2 ? (t == 0 ? 0 : 2) : (city + t) % 3;
        v.tint[t][C_BLONDE] = (uint8_t)hair;
        v.tint[t][C_SKIN] = skins[skin][0];
        v.tint[t][C_SKIND] = skins[skin][1];
        if (t >= 2) {
            v.tint[t][C_SHIRT] = S_RIVAL;
            v.tint[t][C_SHIRTD] = S_RIVALD;
        }
    }
}

/* ---- dirty rows ---------------------------------------------------------------------- */

static void mark_span(int y, int x0, int x1) {
    if (y < 0 || y >= H || v.dirty[y] == 1) return;
    if (x0 < 0) x0 = 0;
    if (x1 > W) x1 = W;
    if (x0 >= x1) return;
    if (v.dirty[y] == 0) {
        v.dirty[y] = 2;
        v.rx0[y] = (int16_t)x0;
        v.rx1[y] = (int16_t)x1;
    } else {
        if (x0 < v.rx0[y]) v.rx0[y] = (int16_t)x0;
        if (x1 > v.rx1[y]) v.rx1[y] = (int16_t)x1;
    }
}

static void dirty_all(void) {
    for (int y = 0; y < H; ++y) v.dirty[y] = 1;
}

/* ---- text ------------------------------------------------------------------------------ */

static int text_y0(int cy) { return cy == 0 ? 1 : cy * 8; }

static void text_dirty(int cy) {
    int y0 = text_y0(cy), y1 = y0 + (v.big[cy] ? 16 : 8);
    for (int y = y0; y < y1; ++y) mark_span(y, 0, W);
}

static void text_clear_line(int cy) {
    int changed = v.panel1[cy] != 0 || v.big[cy];
    for (int x = 0; x < TEXT_COLS; ++x) {
        if (v.text[cy][x] != ' ') changed = 1;
        v.text[cy][x] = ' ';
    }
    if (changed) text_dirty(cy);
    v.panel0[cy] = v.panel1[cy] = 0;
    v.big[cy] = 0;
}

static void text_clear(void) {
    for (int cy = 0; cy < TEXT_ROWS; ++cy) text_clear_line(cy);
}

static int text_len(const char *s) {
    int n = 0;
    while (s[n]) ++n;
    return n;
}

static void text_at(int col, int cy, const char *s, int color) {
    for (int i = 0; s[i] && col + i < TEXT_COLS; ++i) {
        if (col + i < 0) continue;
        if (v.text[cy][col + i] != s[i] || v.tcol[cy][col + i] != color) {
            v.text[cy][col + i] = s[i];
            v.tcol[cy][col + i] = (uint8_t)color;
            text_dirty(cy);
        }
    }
}

static void text_center(int cy, const char *s, int color) {
    int cols = v.big[cy] ? 20 : TEXT_COLS;
    text_at((cols - text_len(s)) / 2, cy, s, color);
}

static void text_panel(int cy0, int cy1, int col0, int col1) {
    for (int cy = cy0; cy <= cy1; ++cy) {
        if (v.panel0[cy] != col0 || v.panel1[cy] != col1) text_dirty(cy);
        v.panel0[cy] = (uint8_t)col0;
        v.panel1[cy] = (uint8_t)col1;
    }
}

static void text_big(int cy, const char *s, int color) {
    text_clear_line(cy);
    text_clear_line(cy + 1);
    v.big[cy] = 1;
    text_center(cy, s, color);
    text_dirty(cy);
}

static const uint8_t *glyph_of(char c) {
    int k = (int)(unsigned char)c - 32;
    if (k >= 64) k -= 32;                         /* lower case as capitals */
    return font_bits + ((k < 0 || k >= 64) ? 0 : k) * 8;
}

static void draw_text_row(uint8_t *line, int y) {
    int cy, row;
    if (v.hud && y < G_HUD_H) {
        cy = 0;
        row = y - 1;
        if (row < 0 || row > 7) return;
    } else {
        cy = y >> 3;
        row = y & 7;
        if (v.hud && cy == 1) return;
    }
    if (v.panel1[cy]) {
        int x0 = v.panel0[cy] * 8, x1 = v.panel1[cy] * 8;
        for (int x = x0; x < x1; ++x) line[x] = C_PANEL;
        if (row == 0 && (cy == 0 || !v.panel1[cy - 1])) for (int x = x0; x < x1; ++x) line[x] = C_PANELL;
        if (row == 7 && (cy == TEXT_ROWS - 1 || !v.panel1[cy + 1])) for (int x = x0; x < x1; ++x) line[x] = C_PANELL;
    }
    if (cy > 0 && v.big[cy - 1]) {
        cy -= 1;
        row += 8;
    }
    if (v.big[cy]) {
        int gy = row >> 1, shadow = (row - 2) >> 1;
        for (int c = 0; c < 20; ++c) {
            char ch = v.text[cy][c];
            if (ch == ' ') continue;
            const uint8_t *gl = glyph_of(ch);
            unsigned bits = gl[gy], under = row >= 2 ? gl[shadow] : 0;
            int left = c * 16, color = v.tcol[cy][c];
            for (int k = 0; k < 8; ++k) {
                int px = left + k * 2;
                if ((under >> (7 - k)) & 1u) line[px + 2] = line[px + 3] = C_INK;
                if ((bits >> (7 - k)) & 1u) line[px] = line[px + 1] = (uint8_t)color;
            }
        }
        return;
    }
    int panel = v.panel1[cy] != 0 || (v.hud && cy == 0);
    for (int c = 0; c < TEXT_COLS; ++c) {
        char ch = v.text[cy][c];
        if (ch == ' ') continue;
        const uint8_t *gl = glyph_of(ch);
        unsigned bits = gl[row], under = row > 0 ? gl[row - 1] : 0;
        int left = c * 8, color = v.tcol[cy][c];
        for (int k = 0; k < 8; ++k) {
            /* Over the picture, letters get a shadow so they read on any background. */
            if (!panel && ((under >> (7 - k)) & 1u)) line[left + k + 1] = C_INK;
            if ((bits >> (7 - k)) & 1u) line[left + k] = (uint8_t)color;
        }
    }
}

/* ---- sprites ---------------------------------------------------------------------------- */

static void sprite_add(int id, int x, int y, int w, int h, int tint, int flip, int depth) {
    if (v.count == MAX_SPRITES || w < 1 || h < 1) return;
    if (x + w <= 0 || x >= W || y >= H || y + h <= 0) return;
    spr_t *s = &v.cur[v.count++];
    s->id = (uint8_t)id;
    s->x = (int16_t)x;
    s->y = (int16_t)y;
    s->w = (int16_t)w;
    s->h = (int16_t)h;
    s->stepx = (uint16_t)(((unsigned)spr_w[id] << 8) / (unsigned)w);
    s->stepy = (uint16_t)(((unsigned)spr_h[id] << 8) / (unsigned)h);
    s->tint = (uint8_t)tint;
    s->flip = (uint8_t)flip;
    s->depth = (int16_t)depth;
}

static void sprite_add_1x(int id, int x, int y, int depth) {
    sprite_add(id, x, y, spr_w[id], spr_h[id], TINT_NONE, 0, depth);
}

/* A run-length row: (index << shift) | run, or run 0 and the run in the next byte. */
static void decode_row(const uint8_t *data, uint8_t *out, int width, int shift) {
    int x = 0;
    unsigned mask = (1u << shift) - 1u;
    while (x < width) {
        unsigned b = *data++;
        unsigned run = b & mask;
        uint8_t value = (uint8_t)(b >> shift);
        if (!run) run = *data++;
        while (run-- && x < width) out[x++] = value;
    }
}

static void blit_sprite_row(const spr_t *s, uint8_t *line, int y) {
    int id = s->id;
    int sy = ((y - s->y) * s->stepy) >> 8;
    if (sy >= spr_h[id]) sy = spr_h[id] - 1;
    decode_row(spr_data + spr_rows[spr_first[id] + sy], v.src, spr_w[id], 3);
    int x = s->x;
    int dx0 = 0, dx1 = s->w;
    if (x < 0) dx0 = -x;
    if (x + dx1 > W) dx1 = W - x;
    const uint8_t *tint = s->tint < TINT_NONE ? v.tint[s->tint] : 0;
    uint8_t *dst = line + x + dx0;
    int last = spr_w[id] - 1;
    for (int dx = dx0; dx < dx1; ++dx) {
        unsigned sx = ((unsigned)dx * s->stepx) >> 8;
        if ((int)sx > last) sx = (unsigned)last;
        uint8_t c = v.src[s->flip ? last - (int)sx : (int)sx];
        if (c != SPR_TRANSPARENT) *dst = tint ? tint[c] : c;
        ++dst;
    }
}

static void send_row(const uint8_t *line, int y, int x0, int x1) {
    int runs = 1;
    for (int x = x0 + 1; x < x1 && runs <= MAX_ROW_RUNS; ++x) runs += line[x] != line[x - 1];
    if (runs > MAX_ROW_RUNS) {
        v.row.pixels = line + x0;
        v.row.width = (uint16_t)(x1 - x0);
        prg32_sprite_draw_indexed(x0, y, &v.row, 0);
        return;
    }
    int x = x0;
    while (x < x1) {
        uint8_t color = line[x];
        int end = x + 1;
        while (end < x1 && line[end] == color) ++end;
        prg32_gfx_rect_indexed(x, y, end - x, 1, v.cell[color]);
        x = end;
    }
}

static void draw_row(int y, int x0, int x1) {
    uint8_t *line = v.line;
    if (v.hud && y < G_HUD_H) {
        for (int x = 0; x < W; ++x) line[x] = y == G_HUD_H - 1 ? C_HUDLINE : C_HUDBAR;
    } else if (y < G_COURT_Y) {
        int r = y - G_VIEW_Y;
        if (r < 0) r = 0;
        int sc = v.city * 2 + v.rev;
        decode_row(view_data + view_rows[sc * G_VIEW_H + r], line, W, 2);
        const uint8_t *map = view_map + sc * 64;
        for (int x = 0; x < W; ++x) line[x] = map[line[x]];
    } else {
        decode_row(court_data + court_rows[v.court * COURT_ROWS + (y - G_COURT_Y)], line, W, 2);
        if (v.rev) {
            /* From the far end the court is the same, turned round: the umpire's
             * chair and the stands change sides. */
            for (int a = 0, b = W - 1; a < b; ++a, --b) {
                uint8_t t = line[a];
                line[a] = line[b];
                line[b] = t;
            }
        }
    }
    for (int k = 0; k < v.count; ++k) {
        const spr_t *s = &v.cur[v.order[k]];
        if (y >= s->y && y < s->y + s->h) blit_sprite_row(s, line, y);
    }
    draw_text_row(line, y);
    send_row(line, y, x0, x1);
}

static void mark_sprite(const spr_t *s) {
    int y0 = s->y < 0 ? 0 : s->y, y1 = s->y + s->h;
    if (y1 > H) y1 = H;
    for (int y = y0; y < y1; ++y) mark_span(y, s->x, s->x + s->w);
}

static void render(void) {
    /* Depth order, far to near: insertion sort of a handful. */
    for (int i = 0; i < v.count; ++i) {
        int k = i;
        while (k > 0 && v.cur[v.order[k - 1]].depth > v.cur[i].depth) {
            v.order[k] = v.order[k - 1];
            --k;
        }
        v.order[k] = (uint8_t)i;
    }
    int n = v.count > v.prev_count ? v.count : v.prev_count;
    for (int i = 0; i < n; ++i) {
        if (i < v.count && i < v.prev_count) {
            const spr_t *a = &v.cur[i], *b = &v.prev[i];
            if (a->id == b->id && a->x == b->x && a->y == b->y && a->w == b->w && a->h == b->h &&
                a->tint == b->tint && a->flip == b->flip && a->depth == b->depth) continue;
        }
        if (i < v.count) mark_sprite(&v.cur[i]);
        if (i < v.prev_count) mark_sprite(&v.prev[i]);
    }
    int sent = 0;
    for (int y = 0; y < H; ++y) {
        if (v.dirty[y]) {
            int whole = v.dirty[y] == 1;
            draw_row(y, whole ? 0 : v.rx0[y], whole ? W : v.rx1[y]);
            v.dirty[y] = 0;
            sent = 1;
        }
        /* Two boxes a frame, no more: on the board a present has a fixed cost, and the
         * far and near halves of the court rarely change together over all rows. */
        if (sent && y == SPLIT_Y - 1) {
            prg32_gfx_present();
            sent = 0;
        }
    }
    for (int i = 0; i < v.count; ++i) v.prev[i] = v.cur[i];
    v.prev_count = v.count;
}

/* ---- the scene ---------------------------------------------------------------------------- */

/* The stadium of `city`, from the broadcast camera or (rev) from the far end. */
static void scene_view(int city, int rev) {
    int key = city * 2 + (rev ? 1 : 0);
    if (key != v.scene_city) {
        v.scene_city = (uint8_t)key;
        city_load(city, rev ? 1 : 0);
        dirty_all();
    }
}

static void scene(int city) { scene_view(city, 0); }

static void add_static(void) {
    sprite_add_1x(SPR_NET, NET_X, NET_Y, 0);
    for (int k = 0; k < BOARD_SLOTS; ++k) sprite_add_1x(SPR_BOARD0 + (v.city + k) % SPONSOR_COUNT, board_x[k], BOARD_Y, -32000);
}

static int player_frame(const az_player_t *p, int t) {
    if (p->cheer) return (t >> 3) & 1 ? PF_CHEER : PF_READY;
    if (p->swing) {
        if (p->shot == SHOT_SERVE || p->shot == SHOT_SMASH) return p->swing < 4 ? PF_SMASH : PF_FOLLOW;
        if (p->swing < AZ_SWING_OPEN + 2) return PF_BACK;
        if (p->swing < AZ_SWING_OPEN + 6) return PF_HIT;
        return PF_FOLLOW;
    }
    return -1;
}

static void add_player(int i) {
    const az_game_t *g = &v.game;
    const az_player_t *p = &g->p[i];
    if (!p->active) return;
    /* Seen from the far end, the world is turned round the centre of the court. */
    int wx = v.rev ? -p->x : p->x, wy = v.rev ? -p->y : p->y;
    int near = (p->team == AZ_NEAR) != (v.rev != 0);
    int frame = player_frame(p, v.app_tick);
    if (frame < 0) {
        if (g->state == PS_SERVE && i == g->server && (g->ball.tossed || g->ball.held)) frame = g->ball.tossed ? PF_TOSS : PF_READY;
        else if (p->moving) frame = (p->step >> 2) & 1 ? PF_RUN1 : PF_RUN2;
        else frame = PF_READY;
    }
    int id = (near ? SPR_BACK_READY : SPR_FRONT_READY) + frame;
    int h = az_px(232, wy);
    int w = spr_w[id] * h / spr_h[id];
    int sx = az_sx(wx, wy), sy = az_sy(wy, 0);
    int flip = p->swing ? p->backhand : 0;
    int sw = az_px(78, wy), sh = sw / 4 + 1;
    sprite_add(SPR_SHADOW, sx - sw / 2, sy - sh / 2, sw, sh, TINT_NONE, 0, -31000);
    sprite_add(id, sx - w / 2, sy - h + 1, w, h, i, flip, wy);
}

static void add_ball(void) {
    const az_ball_t *b = &v.game.ball;
    int x = b->x / AZ_Q, y = b->y / AZ_Q, z = b->z / AZ_Q;
    if (z < 0) z = 0;
    if (v.rev) {
        x = -x;
        y = -y;
    }
    int size = az_px(19, y);
    if (size < 3) size = 3;
    int sx = az_sx(x, y), sy = az_sy(y, z);
    /* In the hand the ball is drawn in front of the server. */
    int depth = y + (b->held ? 40 : 1);
    if (!b->held) {
        int gy = az_sy(y, 0), sw = size + 1;
        sprite_add(SPR_BSHADOW, sx - sw / 2, gy - 1, sw, 2, TINT_NONE, 0, -30000);
    }
    sprite_add(SPR_BALL, sx - size / 2, sy - size / 2, size, size, TINT_NONE, 0, depth);
}

static void add_match(void) {
    add_static();
    for (int i = 0; i < 4; ++i) add_player(i);
    add_ball();
}

