static void points_text(char *out, int team) {
    const az_game_t *g = &v.game;
    int a = g->points[team], b = g->points[1 - team];
    if (g->tiebreak) {
        int k = 0;
        if (a >= 10) out[k++] = (char)('0' + a / 10);
        out[k++] = (char)('0' + a % 10);
        out[k] = 0;
        return;
    }
    static const char names[5][3] = {"0", "15", "30", "40", "AD"};
    int n = a;
    if (a >= 3 && b >= 3) n = a > b ? 4 : 3;
    if (a >= 3 && b >= 3 && a < b) n = 3;
    out[0] = names[n][0];
    out[1] = names[n][1];
    out[2] = 0;
}

static const char *team_name(int team) { return team == 0 ? "AZZURRA" : "RIVALS"; }

static void hud_update(void) {
    const az_game_t *g = &v.game;
    char line[TEXT_COLS + 1];
    for (int i = 0; i < TEXT_COLS; ++i) line[i] = ' ';
    line[TEXT_COLS] = 0;
    /* The team at the near end of the screen is on the left. */
    int lt = v.rev ? 1 : 0, rt = 1 - lt;
    char p0[3], p1[3];
    points_text(p0, lt);
    points_text(p1, rt);
    int serving = g->p[g->server].team;
    /* AZZURRA 2  40 ...  city  ... 15  1 RIVALS */
    const char *a = team_name(lt);
    for (int i = 0; a[i]; ++i) line[1 + i] = a[i];
    line[0] = serving == lt ? '*' : ' ';
    line[9] = (char)('0' + g->games[lt] % 10);
    line[11] = p0[0];
    line[12] = p0[1] ? p0[1] : ' ';
    /* The right-hand name ends at column 38 and its serve mark is at 39; a name of
     * seven letters ends at 39 instead, with the mark before it. */
    const char *r = team_name(rt);
    int rl = text_len(r), r0 = rl > 6 ? 33 : 39 - rl, mark = rl > 6 ? 32 : 39;
    for (int i = 0; r[i]; ++i) line[r0 + i] = r[i];
    line[mark] = serving == rt ? '*' : ' ';
    line[31] = (char)('0' + g->games[rt] % 10);
    int len1 = p1[1] ? 2 : 1;
    line[29 - len1 + 1] = p1[0];
    if (len1 == 2) line[29] = p1[1];
    const char *c = city_names[v.city];      /* in an exhibition and the demo too */
    if (g->tiebreak) c = "TIE-BREAK";
    int cl = text_len(c);
    if (cl > 14) cl = 14;
    int c0 = 14 + (14 - cl) / 2;
    for (int i = 0; i < cl; ++i) line[c0 + i] = c[i];
    for (int i = 0; i < TEXT_COLS; ++i) {
        int color = C_CREAM;
        if (i == 0 || i == mark) color = C_BALL;
        else if (i >= 1 && i <= 7) color = lt == 0 ? C_CYAN : C_RED;
        else if (i >= r0 && i < r0 + rl) color = lt == 0 ? C_RED : C_CYAN;
        else if (i >= 9 && i <= 12) color = C_WHITE;
        else if (i >= 28 && i <= 31) color = C_WHITE;
        else color = C_GOLD;
        char s[2] = {line[i], 0};
        text_at(i, 0, s, color);
    }
}

